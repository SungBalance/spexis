import json
import numpy as np
import pandas as pd
import os
import argparse

# Replace with the path to your JSONL file
parser = argparse.ArgumentParser(description="Throughput saturation analysis")
parser.add_argument("--temp-log-path", type=str, required=True,
					help="Path to temporary log file generated by benchmark script")
parser.add_argument('--batch-size',type=int)
parser.add_argument('--drop-ratio', type=float, default=0.0, help="Drop ratio for the experiment")

args = parser.parse_args()

log_path = args.temp_log_path
bs = args.batch_size
eff_bs = bs - int(bs * args.drop_ratio)



specinfo_list = []
scheduleinfo_list = []

iters = []
hit_ratios = []
batch_sizes = []
spec_diff = []
cpu_emb_times = []

correct_total = 0
wrong_total = 0
flush_total = 0
drop_total = 0


generated_tokens = 0
start_time = 0
end_time = 0
num_iter = 0



with open(log_path, "r", encoding="utf-8") as f:
	for line in f:
		if not line.strip():
			continue

		try:
			entry = json.loads(line)
		except json.JSONDecodeError as e:
			# print error and continue
			print(f"[Warning] Malformed JSON line found. Skipping... Bad content: {line.strip()[:50]}...")
			continue

		iters.append(entry['iter'])

		# Calculate spec hit ratio: correct / (correct + wrong)
		spec = entry.get('spec', {})
		correct = spec.get('correct', 0)
		wrong = spec.get('wrong', 0)
		total = correct + wrong

		correct_total += correct
		wrong_total += wrong
		flush_total += spec.get('flush_norm', 0) + spec.get('flush_drop', 0)
		drop_total += spec.get('final_drop', 0)

		hr = correct / total if total > 0 else np.nan

		sched = entry['sched']

		cpu_emb = entry.get("cpu_embed_s")
		if cpu_emb:
			cpu_emb_times.append(cpu_emb["update_states"] + cpu_emb["reorder"]
			                     + cpu_emb["lookup"])

		num_tokens = sched['tokens']
		if num_tokens == 0:
			continue

		if num_tokens == eff_bs and start_time == 0:
			start_time = entry['time']

		if start_time != 0:
			if num_tokens != eff_bs:
				break
			generated_tokens += (correct + wrong)
			num_iter += 1
			end_time = entry["time"]
			
			if num_iter == 50:
				break



		hit_ratios.append(hr)

	throughput = generated_tokens / (end_time-start_time)

	hit_ratio = correct_total / (correct_total+wrong_total)
	drop_ratio = drop_total / (correct_total+wrong_total+flush_total+drop_total)
	average_cpu_emb_time = np.mean(cpu_emb_times) if len(cpu_emb_times) > 0 else 0

	if num_iter != 50:
		print(f"[Warning] Only {num_iter} iterations were processed. Expected 50 iterations.")

	print(f"Iters: {num_iter}")
	print(f"{throughput} token/s") 
	print(f"Spec Accuracy: {hit_ratio*100}%")
	print(f"Drop Ratio: {drop_ratio*100}%")
	print(f"{average_cpu_emb_time*1000} ms")
        

