import json
import numpy as np
import pandas as pd
import os

import argparse

parser = argparse.ArgumentParser(description="Throughput saturation analysis")
parser.add_argument("--temp-log-path", type=str, required=True,
					help="Path to temporary log file generated by benchmark script")
parser.add_argument('--batch-size',type=int)
parser.add_argument('--pp-size', type=int, default=1,)

args = parser.parse_args()

## can not handle same micro-batch size eg) 64 64 -> catch 63 61 (after finish some requests)

log_path = args.temp_log_path
bs = args.batch_size
pp_size = args.pp_size

specinfo_list = []
scheduleinfo_list = []

iters = []
hit_ratios = []
batch_sizes = []
spec_diff = []

correct_total = 0
wrong_total = 0


generated_tokens = 0
start_time = 0
end_time = 0

duplicate = 0

micro_batch_pair = []

effective_iter = 0

with open(log_path, "r", encoding="utf-8") as f:
	for line in f:
		if not line.strip():
			continue

		try:
			entry = json.loads(line)
		except json.JSONDecodeError as e:
			# print error and continue
			print(f"[Warning] Malformed JSON line found. Skipping... Bad content: {line.strip()[:50]}...")
			continue

		iter = entry['iter']
		iters.append(entry['iter'])


		sched = entry['sched']

		# pass if no tokens scheduled
		if sched['tokens'] == 0:
			continue
		
		# hard code to pass the first 5 iterations to avoid small prefill requests
		if iter > 138:
			if start_time==0 and sched['tokens'] <= bs/pp_size:
				start_time = entry['time']
		
		if start_time != 0:
			if effective_iter<pp_size:
				micro_batch_pair.append(sched['tokens'])
			else:
				# if mismatch with micro batch size, stop
				if micro_batch_pair[effective_iter%pp_size] != sched['tokens']:
					break
					
			generated_tokens += sched['tokens']

			effective_iter+=1
			
			end_time = entry["time"]

	ub_sum = 0
	for i in range(pp_size):
		ub_sum += micro_batch_pair[i]

	if ub_sum != bs:
		print(f"Invalid Experiment: Sum u-bs != # req ({ub_sum} != {bs})")

	throughput = generated_tokens / (end_time-start_time)

	print(f"Micro-batch sizes: {micro_batch_pair}")

	print(f"{throughput} token/s") 

        

