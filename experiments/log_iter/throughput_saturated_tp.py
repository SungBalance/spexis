import json
import numpy as np
import pandas as pd
import os

import argparse

parser = argparse.ArgumentParser(description="Throughput saturation analysis")
parser.add_argument("--temp-log-path", type=str, required=True,
					help="Path to temporary log file generated by benchmark script")
parser.add_argument('--batch-size',type=int)
parser.add_argument('--pp-size', type=int, default=1,) # for using the same format with pp / not used
parser.add_argument('--skip-iters', type=int, default=10,
					help="Skip this many warmup iterations before measuring")
parser.add_argument('--num-iters', type=int, default=50,
					help="Number of consecutive full-batch iterations to measure")

args = parser.parse_args()

log_path = args.temp_log_path
bs = args.batch_size

specinfo_list = []
scheduleinfo_list = []

iters = []
hit_ratios = []
batch_sizes = []
spec_diff = []

correct_total = 0
wrong_total = 0

num_iter = 0


generated_tokens = 0
start_time = 0
end_time = 0

duplicate = 0

effective_iter = 0

with open(log_path, "r", encoding="utf-8") as f:
	for line in f:
		if not line.strip():
			continue

		try:
			entry = json.loads(line)
		except json.JSONDecodeError as e:
			# print error and continue
			print(f"[Warning] Malformed JSON line found. Skipping... Bad content: {line.strip()[:50]}...")
			continue

		iter = entry['iter']
		iters.append(entry['iter'])

		sched = entry['sched']

		# pass if no tokens scheduled
		if sched['tokens'] == 0:
			continue
		
		# Skip the warmup/prefill iterations before starting the window.
		if iter > args.skip_iters:
			if start_time==0 and sched['tokens'] == bs:
				start_time = entry['time']

		if start_time != 0:
			if sched['tokens'] != bs:
				break
			generated_tokens += sched['tokens']
			num_iter += 1
			end_time = entry["time"]
			
			if num_iter == args.num_iters:
				break
	
	throughput = generated_tokens / (end_time-start_time)

	if num_iter != args.num_iters:
		print(f"[Warning] Only {num_iter} iterations were processed. Expected {args.num_iters} iterations.")

	print(f"Iters: {num_iter}")
	print(f"{throughput} token/s") 
